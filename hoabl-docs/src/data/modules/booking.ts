const id = (): Column => ({ name: 'id', type: 'uuid', pk: true, default: 'gen_random_uuid()' });
const fk = (name: string, table: string, extra: Partial<Column> = {}): Column => ({
  name,
  type: 'uuid',
  fk: { table, column: 'id' },
  ...extra,
});
const col = (name: string, type: string, description?: string, extra: Partial<Column> = {}): Column => ({
  name,
  type,
  description,
  ...extra,
});
const createdAt = (): Column =>
  col('created_at', 'timestamptz', 'Row creation time', { default: 'now()' });

