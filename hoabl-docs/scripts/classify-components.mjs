#!/usr/bin/env node
/**
 * Builds src/data/components/components.ts: every LWC and Visualforce page in the retrieved source,
 * with its API name and Apex controller(s), and the module pages it belongs to.
 *
 *   node scripts/classify-components.mjs [path-to-force-app/main/default]
 *
 * Re-run after every retrieve (and after src/data/apex/<module>.ts changes).
 *
 * Module assignment: each controller votes for the module pages that document it, weighted 1/N when N pages
 * document it (so a class unique to one module counts more than a shared one). The component goes to the
 * top-scoring module; ties go to every tied module. `src/data/components/pins.json` adds hand-curated
 * memberships on top, so names already listed on a page never disappear.
 * Components with no Apex controller (pure UI, standard controllers) can only appear through a pin.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2] ?? process.env.HOABL_SFDX ?? 'C:/Users/Admin/Desktop/HOABL/hoabl-prod/force-app/main/default';
const OUT = path.join(ROOT, 'src/data/components/components.ts');

const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
const exists = (p) => fs.existsSync(path.join(SRC, p));
const read = (p) => fs.readFileSync(path.join(SRC, p), 'utf8');

const apexNames = new Set(fs.readdirSync(path.join(SRC, 'classes')).filter((f) => f.endsWith('.cls')).map((f) => f.slice(0, -4)));
const byLower = new Map([...apexNames].map((n) => [n.toLowerCase(), n]));
const canon = (n) => byLower.get(n.trim().toLowerCase());

// module -> documented Apex class names
const moduleApex = {};
const apexDir = path.join(ROOT, 'src/data/apex');
for (const f of fs.readdirSync(apexDir).filter((f) => f.endsWith('.ts') && !/^(index|types|classification)\.ts$/.test(f)))
  moduleApex[f.slice(0, -3)] = new Set([...fs.readFileSync(path.join(apexDir, f), 'utf8').matchAll(/"name": "([^"]+)"/g)].map((m) => m[1]));

const pins = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/components/pins.json'), 'utf8'));

// How many module pages document each class. A class on one page is a strong signal; one on five is weak.
const spread = {};
for (const set of Object.values(moduleApex)) for (const c of set) spread[c] = (spread[c] ?? 0) + 1;

function assign(controllers, pinned = []) {
  const score = Object.entries(moduleApex)
    .map(([m, set]) => [m, controllers.filter((c) => set.has(c)).reduce((sum, c) => sum + 1 / spread[c], 0)])
    .filter(([, n]) => n > 0);
  const top = Math.max(0, ...score.map(([, n]) => n));
  const modules = new Set(score.filter(([, n]) => Math.abs(n - top) < 1e-9).map(([m]) => m));
  for (const m of pinned) modules.add(m);
  return [...modules].sort();
}

// ---- LWC
const lwc = [];
for (const d of fs.readdirSync(path.join(SRC, 'lwc'), { withFileTypes: true }).filter((e) => e.isDirectory())) {
  const controllers = new Set();
  for (const f of fs.readdirSync(path.join(SRC, 'lwc', d.name)).filter((f) => f.endsWith('.js')))
    for (const m of strip(read(`lwc/${d.name}/${f}`)).matchAll(/@salesforce\/apex\/(\w+)\./g)) {
      const c = canon(m[1]);
      if (c) controllers.add(c);
    }
  const cs = [...controllers].sort((a, b) => a.localeCompare(b));
  const modules = assign(cs, pins.lwc[d.name]);
  if (modules.length) lwc.push({ name: d.name, controllers: cs, modules });
}

// ---- Visualforce pages
const vf = [];
for (const f of fs.readdirSync(path.join(SRC, 'pages')).filter((f) => f.endsWith('.page'))) {
  const name = f.slice(0, -5);
  const markup = read(`pages/${f}`);
  const tag = markup.match(/<apex:page\b[^>]*>/is)?.[0] ?? '';
  const attr = (a) => tag.match(new RegExp(`(?<![A-Za-z])${a}\\s*=\\s*"([^"]+)"`, 'i'))?.[1];
  const controllers = new Set();
  for (const raw of [attr('controller'), ...(attr('extensions')?.split(',') ?? [])]) {
    const c = raw && canon(raw);
    if (c) controllers.add(c);
  }
  const standard = tag.match(/standardController\s*=\s*"([^"]+)"/i)?.[1];
  const cs = [...controllers].sort((a, b) => a.localeCompare(b));
  const modules = assign(cs, pins.vf[name]);
  if (modules.length) vf.push({ name, controllers: cs, ...(standard ? { standard } : {}), modules });
}

const byName = (a, b) => a.name.localeCompare(b.name);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/classify-components.mjs from the retrieved Salesforce source. Do not edit by hand.
import type { ComponentInfo } from './types';

export const lwcComponents: ComponentInfo[] = ${JSON.stringify(lwc.sort(byName), null, 2)};

export const vfPages: ComponentInfo[] = ${JSON.stringify(vf.sort(byName), null, 2)};
`,
);

const perModule = (list) => Object.fromEntries(Object.keys(moduleApex).map((m) => [m, list.filter((c) => c.modules.includes(m)).length]));
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${lwc.length} LWCs, ${vf.length} Visualforce pages`);
console.log('LWC per module', perModule(lwc));
console.log('VF  per module', perModule(vf));
